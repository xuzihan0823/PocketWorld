"""Fit Luna's book contacts on the cardigan skin. Run with Blender 5.2 in background.

--palm-output exports the Blender palm guides for procedural page/cover IK.
--pickup-output exports only the corrected joint rotations for the embedded clip.
--blend saves the fitted actions for further editing; --from-blend re-exports them.
"""
import argparse
import json
import math
from pathlib import Path
import struct
import sys

import bpy
from mathutils import Matrix, Quaternion, Vector

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / 'assets/public/models/resident/luna-cardigan.glb'
SCALE = 1.43
Z_UP = Matrix.Rotation(math.pi / 2, 4, 'X')
# The animated resident faces the shelf from 58 cm away, facing local -Z.
ACTOR = Matrix.Translation((0, -0.58, 0)) @ Matrix.Rotation(math.pi, 4, 'Z') @ Matrix.Scale(SCALE, 4)
SIDES = ('Right', 'Left')
JOINTS = [side + part for side in SIDES for part in ('Arm', 'ForeArm', 'Hand')]


def smooth(value, start, end):
    t = min(1, max(0, (value - start) / (end - start)))
    return t*t*(3 - 2*t)


def palm_basis(forward, across, side):
    y = -forward.normalized()
    z = across.cross(-y).normalized() * (1 if side == 'Right' else -1)
    x = y.cross(z).normalized()
    return Matrix((x, y, x.cross(y))).transposed().to_quaternion()


def save_data(path, variable, value):
    text = '// Generated by scripts/bake-cardigan-library-hands.py. Units are metres and XYZW quaternions.\n'
    path.write_text(text + 'export const ' + variable + ' = ' + json.dumps(value, separators=(',', ':')) + ';\n', encoding='utf-8')


def xyzw(rotation):
    return [round(x, 7) for x in (rotation.x, rotation.y, rotation.z, rotation.w)]


def calibrate(rig, create=True):
    output = []
    for side in SIDES:
        at = lambda part: rig.data.bones['mixamorig:' + side + part].head_local
        wrist = at('Hand')
        across = at('HandIndex1') - at('HandPinky1')
        previous = palm_basis(at('HandMiddle1') - wrist, across, side)
        knuckles = (at('HandIndex1') + at('HandPinky1')) / 2 - wrist
        if create:
            guide = bpy.data.objects.new(side + 'PalmBearing', None)
            bpy.context.scene.collection.objects.link(guide)
            guide.empty_display_type = 'ARROWS'
            guide.empty_display_size = .025
            guide.rotation_mode = 'QUATERNION'
            guide.rotation_quaternion = palm_basis(knuckles, across, side)
            # Offset from the wrist to the loaded pad, in the binding frame.
            guide.location = wrist + knuckles*.55 + guide.rotation_quaternion @ Vector((0, 0, .012 / SCALE))
            guide['openPadDepth'] = .0101 if side == 'Right' else .0090
        else:
            guide = bpy.data.objects[side + 'PalmBearing']
        output.append({'openPadDepth': round(guide['openPadDepth'], 7), 'basis': xyzw(previous.inverted() @ guide.rotation_quaternion),
                       'offset': [round(x, 7) for x in (previous.inverted() @ (guide.location - wrist)) * SCALE]})
    return output


def imported_model():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.context.scene.render.fps = 30
    bpy.ops.import_scene.gltf(filepath=str(MODEL))
    rig = next(o for o in bpy.context.scene.objects if o.type == 'ARMATURE')
    return rig, bpy.data.objects['LibraryBook']


def bind_frames(rig):
    raw = MODEL.read_bytes()
    size = struct.unpack_from('<I', raw, 12)[0]
    doc = json.loads(raw[20:20+size]); skin = doc['skins'][0]
    accessor = doc['accessors'][skin['inverseBindMatrices']]
    start = 28 + size + doc['bufferViews'][accessor['bufferView']].get('byteOffset', 0) + accessor.get('byteOffset', 0)
    correction = {}
    for i, node in enumerate(skin['joints']):
        name = doc['nodes'][node]['name']
        values = struct.unpack_from('<16f', raw, start + i*64)
        inv_bind = Matrix([values[j:j+4] for j in range(0, 16, 4)]).transposed()
        correction[name] = inv_bind @ Z_UP.inverted() @ rig.data.bones[name].matrix_local
    return correction


def select_action(owner, action):
    ad = owner.animation_data_create()
    ad.use_nla = False
    ad.action = action
    ad.action_slot = next(slot for slot in action.slots if slot.name_display == owner.name)


def skin_patches(mesh, rig):
    groups = {g.index: g.name for g in mesh.vertex_groups}
    def ids(side):
        return [v.index for v in mesh.data.vertices if groups[max(v.groups, key=lambda g: g.weight).group].startswith('mixamorig:'+side+'Hand')]
    right = ids('Right')
    pads = {}
    for digit in ('Index', 'Middle', 'Ring', 'Pinky', 'Thumb'):
        point = rig.data.bones['mixamorig:RightHand'+digit+'4'].head_local
        pads[digit] = sorted(right, key=lambda i:(mesh.data.vertices[i].co - point).length_squared)[:12]
    return pads, ids('Left')


def contact_distance(points, direction):
    # First intersection of the bearing skin with either closed cover or the page block.
    nearest = math.inf
    for low, high in [((0,-.006,-.11),(.24,.006,.11)), ((0,.052,-.11),(.24,.064,.11)),
                      ((.008,.006,-.104),(.232,.052,.104))]:
        for point in points:
            near, far = -math.inf, math.inf
            for x, d, lo, hi in zip(point, direction, low, high):
                if abs(d)<1e-6:
                    if x < lo or x > hi:
                        near = math.inf; break
                else:
                    t, u = (lo-x)/d, (hi-x)/d
                    near, far = max(near, min(t,u)), min(far, max(t,u))
            if near <= far and far >= -.018:
                nearest = min(nearest, near)
    return max(-.08, min(.08, nearest)) if math.isfinite(nearest) else 0


def fit_grip(rig, surface, pads, book_frame):
    # Finger weights overlap on this model. Fit the actual pad vertices jointly;
    # rotating an index joint alone moves almost none of the visible index pad.
    import numpy as np
    joints = [rig.pose.bones['mixamorig:RightHand'+d+'1'] for d in pads]
    starts = [b.rotation_quaternion.copy() for b in joints]
    across = (rig.pose.bones['mixamorig:RightHandIndex1'].head - rig.pose.bones['mixamorig:RightHandPinky1'].head).normalized()
    fore = ((rig.pose.bones['mixamorig:RightHandIndex1'].head + rig.pose.bones['mixamorig:RightHandPinky1'].head)*.5-rig.pose.bones['mixamorig:RightHand'].head).normalized()
    axes = [(b.matrix.to_quaternion().inverted() @ across, b.matrix.to_quaternion().inverted() @ fore) for b in joints]
    def pose(params):
        for j, (bone, start, (x, y)) in enumerate(zip(joints, starts, axes)):
            bone.rotation_quaternion = start @ Quaternion(x, params[j*2]) @ Quaternion(y, params[j*2+1])
        bpy.context.view_layer.update()
        ev = surface.evaluated_get(bpy.context.evaluated_depsgraph_get())
        points = {digit: [book_frame @ ev.data.vertices[i].co for i in group] for digit,group in pads.items()}
        return points
    params = np.zeros(10)
    def error(params):
        pts = pose(params)
        heights = np.array([max(p.y for p in pts[d]) for d in ('Index','Middle','Ring','Pinky')])
        # Fit the four pads to one plane. Their common height is solved by the arm.
        # The thumb wraps the spine on the opposite side of that plane.
        thumb = max(pts['Thumb'], key=lambda p:p.x)
        middle = sum(pts['Middle'], Vector()) / len(pts['Middle'])
        return np.r_[heights-heights.mean(), (thumb.y-heights.mean()-.023), thumb.x-middle.x+.040]
    for _ in range(18):
        residual = error(params)
        jac = np.array([(error(params + step*.003)-residual)/.003 for step in np.eye(10)]).T
        delta = np.linalg.lstsq(np.vstack((jac, np.eye(10)*.003)), np.r_[-residual,-params*.00004], rcond=None)[0]
        params = np.clip(params + np.clip(delta,-.10,.10), -.65, .65)
    pose(params)
    return {bone.name:start.inverted() @ bone.rotation_quaternion for bone,start in zip(joints, starts)}


def fit_row(rig, marker, surface, row, correction, handoff):
    import runpy
    Pose = runpy.run_path(str(ROOT/'scripts/bake-luna-library.py'))['Pose']
    scene = bpy.context.scene
    original = bpy.data.actions[f'Library_Pickup_{row}']
    edited = original.copy(); edited.name = f'Cardigan_Book_Hands_{row}'
    edited.use_fake_user = True
    select_action(marker, original); select_action(rig, original)
    bones = {b.name:b for b in rig.pose.bones}
    pads, left_skin = skin_patches(surface, rig)
    scene.frame_set(72)
    grip = fit_grip(rig, surface, pads, (ACTOR.inverted() @ marker.matrix_world @ Z_UP).inverted())
    changed = ['mixamorig:'+j for j in JOINTS] + list(grip)
    handoff_frames = {name: Matrix.Scale(1/SCALE,4) @ Z_UP @ Matrix([value[i:i+4] for i in range(0,16,4)]).transposed() @ correction[name]
                      for name in bones if (value := handoff.get(name.replace(':','')))}
    keys = []
    for f in range(181):
        scene.frame_set(f)
        grip_load = smooth(f, 26, 60)*(1-smooth(f,132,151))
        for name, delta in grip.items():
            bones[name].rotation_quaternion @= Quaternion().slerp(delta,grip_load)
        bpy.context.view_layer.update()
        ev = surface.evaluated_get(bpy.context.evaluated_depsgraph_get())
        world = {name:b.matrix.copy() for name,b in bones.items()}
        # Pose expects the GLTFLoader-sanitised names used by the everyday bake.
        pose = Pose({name.replace(':',''):b for name,b in bones.items()}, {name.replace(':',''):m for name,m in world.items()})
        to_rig = ACTOR.inverted() @ marker.matrix_world @ Z_UP
        to_book = to_rig.inverted()
        handoff_weight = smooth(f,153,180)
        for side in SIDES:
            upper, lower, wrist = ['mixamorig'+side+part for part in ('Arm','ForeArm','Hand')]
            start, elbow, end = [pose.point(name) for name in (upper,lower,wrist)]
            goal = end.copy(); rotation = pose.rotation(wrist)
            if side == 'Right':
                pts = {d:[to_book @ ev.data.vertices[i].co for i in group] for d,group in pads.items()}
                centre = sum(pts['Middle'],Vector())/len(pts['Middle'])
                top = max(p.y for d in ('Index','Middle','Ring','Pinky') for p in pts[d])
                z = (-.037+.057*smooth(f,108,132)) if row==2 else (.042,.020)[row]
                delta = Vector((.034-centre.x,-.0064-top,z-centre.z))
                goal += to_rig.to_3x3() @ delta * (smooth(f,34,58)*(1-smooth(f,132,156)))
            else:
                pts = [to_book @ ev.data.vertices[i].co for i in left_skin]
                up = (marker.matrix_world @ Z_UP).to_quaternion().inverted() @ Vector((0,0,1))
                # Once the volume is flat, the top of the exposed finger pads
                # bears its underside. Moving in world-up alone misses the near
                # edge while the book tilts and the palm travels around the spine.
                settle = smooth(f,138,155)
                if settle:
                    centre = to_book @ pose.point(wrist+'Middle4')
                    shift = Vector((max(.035,min(.205,centre.x))-centre.x,0,max(-.077,min(.077,centre.z))-centre.z))*settle
                    goal += to_rig.to_3x3() @ shift
                    pts = [p+shift for p in pts]
                gap = contact_distance(pts,up)
                goal += to_rig.to_3x3() @ (up*(gap-.0003)) * smooth(f,100,124)
            final = handoff_frames['mixamorig:'+side+'Hand']
            if side == 'Right':
                goal = goal.lerp(final.translation,handoff_weight)
            rotation = rotation.slerp(final.to_quaternion(),handoff_weight)
            pole = elbow - start
            pose.limb(upper,lower,wrist,goal,pole,keep_bend_plane=True)
            # Move axial rotation out of the wrist without shifting the book or the pads.
            lower_bone = bones['mixamorig:'+side+'ForeArm']; hand_bone = bones['mixamorig:'+side+'Hand']
            bind_hand = lower_bone.bone.matrix_local.inverted() @ hand_bone.bone.matrix_local
            delta = rotation @ (pose.rotation(lower) @ bind_hand.to_quaternion()).inverted()
            axis = (pose.point(wrist)-pose.point(lower)).normalized()
            if delta.w<0: delta.negate()
            twist = 2*math.atan2(Vector((delta.x,delta.y,delta.z)).dot(axis),delta.w)
            share = max(-.65,min(.65,twist)) * smooth(f,8,44) * (1-handoff_weight)
            pose.turn(lower,axis,share)
            if (side == 'Right' and f < 58) or (side == 'Left' and f < 124):
                # Before contact, let the palm follow the approaching forearm.
                knuckles = (pose.point(wrist+'Index1') + pose.point(wrist+'Pinky1'))*.5 - pose.point(wrist)
                forward = rotation @ (pose.rotation(wrist).inverted() @ knuckles).normalized()
                angle = forward.angle(axis)
                if angle > .87:
                    rotation = Quaternion().slerp(forward.rotation_difference(axis),1-.87/angle) @ rotation
            pose.set_rotation(wrist,rotation)
        fitted = {name:pose.matrix(name.replace(':','')) for name in bones}
        local = {}
        for name in changed:
            bone = bones[name]; parent = bone.parent
            basis = bone.bone.convert_local_to_pose(fitted[name],bone.bone.matrix_local,parent_matrix=fitted[parent.name],parent_matrix_local=parent.bone.matrix_local,invert=True)
            q = basis.to_quaternion()
            # Local handoff includes the actual elbow roll and finger curl from the page rig.
            endpoint = bone.bone.convert_local_to_pose(handoff_frames[name],bone.bone.matrix_local,parent_matrix=handoff_frames[parent.name],parent_matrix_local=parent.bone.matrix_local,invert=True)
            local[name] = q.slerp(endpoint.to_quaternion(),smooth(f,170,180) if 'Left' in name else handoff_weight)
        keys.append(local)
    select_action(rig,edited)
    from bpy_extras import anim_utils
    bag = anim_utils.action_get_channelbag_for_slot(edited,rig.animation_data.action_slot)
    for curve in list(bag.fcurves):
        if any(curve.data_path == bones[n].path_from_id('rotation_quaternion') for n in changed): bag.fcurves.remove(curve)
    prev = {}
    for frame,local in enumerate(keys):
        for name,q in local.items():
            if name in prev and q.dot(prev[name])<0:q.negate()
            prev[name]=q.copy();bones[name].rotation_quaternion=q
            bones[name].keyframe_insert('rotation_quaternion',frame=frame,group=name)
    seat_support(rig, marker, surface, left_skin, edited)


def seat_support(rig, marker, surface, left_skin, action):
    import runpy
    Pose = runpy.run_path(str(ROOT/'scripts/bake-luna-library.py'))['Pose']
    select_action(rig, action)
    bones = {b.name.replace(':',''):b for b in rig.pose.bones}
    upper,lower,wrist = ('mixamorigLeft'+s for s in ('Arm','ForeArm','Hand'))
    previous = {}
    for f in [j/4 for j in range(122*4,180*4+1)]:
        bpy.context.scene.frame_set(int(f), subframe=f%1)
        to_rig = ACTOR.inverted() @ marker.matrix_world @ Z_UP
        to_book = to_rig.inverted()
        for _ in range(2):
            ev = surface.evaluated_get(bpy.context.evaluated_depsgraph_get())
            points = [to_book @ ev.data.vertices[i].co for i in left_skin]
            up = (marker.matrix_world @ Z_UP).to_quaternion().inverted() @ Vector((0,0,1))
            # Below the rotating edge, the normal must point into the thinnest
            # face first. Use the hand's own resolved load axis.
            gap = contact_distance(points, up)
            pose = Pose(bones, {n:b.matrix.copy() for n,b in bones.items()})
            goal = pose.point(wrist) + to_rig.to_3x3() @ (up*(gap-.00035))*smooth(f,122,124)
            if f>=179:goal = goal.lerp(pose.point(wrist),smooth(f,178,180))
            rotation = pose.rotation(wrist)
            pose.limb(upper, lower, wrist, goal, pose.point(lower)-pose.point(upper),keep_bend_plane=True)
            pose.set_rotation(wrist,rotation)
            for name in (upper,lower,wrist):
                b=bones[name]
                parent=b.parent.name.replace(':','')
                basis=b.bone.convert_local_to_pose(pose.matrix(name),b.bone.matrix_local,parent_matrix=pose.matrix(parent),parent_matrix_local=b.parent.bone.matrix_local,invert=True)
                b.rotation_quaternion=basis.to_quaternion()
            bpy.context.view_layer.update()
        for name in (upper,lower,wrist):
            b=bones[name]
            if name in previous and previous[name].dot(b.rotation_quaternion)<0:b.rotation_quaternion.negate()
            previous[name]=b.rotation_quaternion.copy()
            b.keyframe_insert('rotation_quaternion',frame=f,group=b.name)



def simplified(samples, frames, tolerance=.0015):
    kept = {0,len(samples)-1}
    def split(a,b):
        if b <= a+1:return
        worst,i = max((samples[a].slerp(samples[b],(frames[j]-frames[a])/(frames[b]-frames[a])).rotation_difference(samples[j]).angle,j) for j in range(a+1,b))
        if worst > tolerance:
            kept.add(i);split(a,i);split(i,b)
    split(0,len(samples)-1)
    return [[frames[i]]+[round(x*32767) for x in xyzw(samples[i])] for i in sorted(kept)]


def export_actions(rig, correction):
    names = ['mixamorig:'+j for j in JOINTS] + ['mixamorig:RightHand'+d+'1' for d in ('Index','Middle','Ring','Pinky','Thumb')]
    result=[]
    for row in range(3):
        select_action(rig,bpy.data.actions[f'Cardigan_Book_Hands_{row}'])
        samples={n:[] for n in names}
        frames = list(range(122)) + [i/4 for i in range(122*4,180*4+1)]
        for f in frames:
            bpy.context.scene.frame_set(int(f), subframe=f%1)
            for name in names:
                b=rig.pose.bones[name];p=b.parent
                q=(correction[p.name] @ p.matrix.inverted() @ b.matrix @ correction[name].inverted()).to_quaternion()
                if samples[name] and q.dot(samples[name][-1])<0:q.negate()
                samples[name].append(q)
        result.append({n.replace(':',''):simplified(values,frames) for n,values in samples.items()})
    return result


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--palm-output', type=Path)
    args.add_argument('--pickup-output', type=Path)
    args.add_argument('--blend', type=Path)
    args.add_argument('--from-blend', type=Path)
    options = args.parse_args(sys.argv[sys.argv.index('--')+1:])
    if options.from_blend:
        bpy.ops.wm.open_mainfile(filepath=str(options.from_blend))
        rig = bpy.data.objects['Luna_Cardigan_Rig']
        if options.palm_output:
            save_data(options.palm_output, 'CARDIGAN_PALMS', calibrate(rig, create=False))
        if options.pickup_output:
            save_data(options.pickup_output, 'CARDIGAN_PICKUP', export_actions(rig, bind_frames(rig)))
        return
    rig, book = imported_model()
    palms = calibrate(rig)
    if options.palm_output:
        save_data(options.palm_output, 'CARDIGAN_PALMS', palms)
    if options.pickup_output:
        import subprocess
        handoff = json.loads(subprocess.check_output(['node', str(ROOT/'scripts/luna-library-neutral.mjs'), '--cardigan', '--handoff'], cwd=ROOT))
        correction = bind_frames(rig)
        surface = bpy.data.objects['Luna_Cardigan']
        for row in range(3):
            fit_row(rig, book, surface, row, correction, handoff)
        save_data(options.pickup_output, 'CARDIGAN_PICKUP', export_actions(rig, correction))
        if options.blend:
            for owner in (rig,book):
                ad=owner.animation_data
                for track in list(ad.nla_tracks):ad.nla_tracks.remove(track)
            active=bpy.data.actions['Cardigan_Book_Hands_1']
            select_action(rig,active);select_action(book,active)
            for action in list(bpy.data.actions):
                if not action.name.startswith('Cardigan_Book_Hands_'):bpy.data.actions.remove(action)
            for mat in surface.data.materials:
                if mat and mat.node_tree:
                    for node in list(mat.node_tree.nodes):
                        if node.type == 'TEX_IMAGE':
                            mat.node_tree.nodes.remove(node)
            for image in list(bpy.data.images):bpy.data.images.remove(image)
            # Display the book in the same armature coordinates as the mesh.
            preview=book.copy();preview.name='Closed book preview';preview.animation_data_clear()
            bpy.context.scene.collection.objects.link(preview)
            book.parent=preview;preview.matrix_world=ACTOR.inverted()
            bpy.ops.mesh.primitive_cube_add(size=1)
            volume=bpy.context.object;volume.name='Closed book';volume.parent=book
            volume.location = Z_UP @ Vector((.12,.029,0))
            volume.scale = (.24,.22,.070)
            cover = bpy.data.materials.new('Cloth book cover')
            cover.diffuse_color = (.18,.32,.25,1)
            volume.data.materials.append(cover)
            rig.show_in_front = False
            bpy.ops.object.select_all(action='DESELECT')
            rig.select_set(True)
            bpy.context.view_layer.objects.active = rig
            for area in bpy.context.screen.areas:
                if area.type == 'VIEW_3D':
                    area.spaces.active.overlay.show_overlays = False
                    view = area.spaces.active.region_3d
                    view.view_distance = .90
                    view.view_location = Vector((0,-.1,.68))
                    view.view_rotation = Vector((-.85,1,-.24)).to_track_quat('-Z','Y')
            bpy.context.scene.frame_start=0;bpy.context.scene.frame_end=180;bpy.context.scene.frame_set(108)
            bpy.context.preferences.filepaths.save_version=0
            bpy.ops.wm.save_as_mainfile(filepath=str(options.blend),compress=True)


if __name__ == '__main__':
    main()
